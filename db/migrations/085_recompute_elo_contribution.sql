-- Решение руководителя (сентябрь 2026) после разбора игры, где первоубиенный сделал большой ЛХ,
-- набрал лучший итог в команде (0.70) и всё равно потерял больше всех (−14.3):
--   1) личный вклад теперь считается как итог игрока за игру без командного балла за победу —
--      допы, минуса, ЛХ, Ci и штрафы. Раньше брались только «+»/«−» судьи, и ЛХ на ELO не влиял;
--   2) вес вклада в дележе командной дельты 0.25 → 0.6 (ELO_CONTRIB): личная игра стала заметна;
--   3) первоубиенному потеря умножается на 0.7 (ELO_PU_LOSS_MULT) — играть ему не дали;
--      выигрыши не режутся.
-- На разобранной игре: −14.3 → −7.4 у первоубиенного с лучшим итогом, при этом поражение всё
-- равно стоит рейтинга, а нулевой игрок команды теряет столько же (−7.8).
--
-- Имя содержит «recompute» — run_migrations() один раз выполнит rating_recompute_all(),
-- а тот пересчитает и ELO по всей истории (elo_recompute). ELO сквозной, менять его задним
-- числом безопасно: elo_history перестраивается целиком.
