-- Начало сезона 2026/2027.
--
-- Клубный (основной) рейтинг — это одна строка ratings с is_main=1: миграция 001 завела
-- её как «Общий рейтинг», 045 переименовала в «Сезон 2025/2026». Авто-переката сезона в
-- коде НЕТ (сезон = 1 сентября–31 августа, current_season_bounds(); сезонные лукапы идут
-- по строке названия — см. CLAUDE.md, «известная мина»). Поэтому 1 сентября 2026 новый
-- сезон сам не начался: рейтинг продолжал показывать 2025/2026, а новые вечера копились бы
-- в прошлый сезон. Владелец подтвердил: нужен новый сезон с нуля, старый — в архив.
--
-- Что делаем:
--   1. Замораживаем прошлый основной сезон: снимаем is_main, ставим is_frozen=1. Кэш
--      (rating_cache) этого сезона остаётся нетронутым — rating_recompute_all() берёт
--      только is_active=1 AND is_frozen=0 (inc/rating.php), так что итоговая таблица
--      2025/2026 застывает как есть. is_active НЕ трогаем: выпадашка сезонов на rating.php
--      строится по WHERE is_active=1, иначе прошлый сезон пропал бы из архива.
--   2. Заводим новый основной сезон «Сезон 2026/2027» — пустой. Клубные баллы, Σ и счётчик
--      игр стартуют с нуля; сезон заполнится с первого сыгранного вечера
--      (day_attach_to_main_rating() привязывает день к is_main=1, т.е. уже к новому сезону).
--
-- ELO НЕ обнуляется — это сквозной карьерный рейтинг: elo_recompute() проигрывает всю
-- историю игр глобально, вне привязки к сезону/is_main. Название нового сезона совпадает с
-- current_season_bounds()[2] = «Сезон 2026/2027», поэтому сезонные лукапы по строке снова
-- попадают в цель (мина закрыта до 1 сентября 2027 — тогда понадобится такой же перекат).
--
-- В имени файла НЕТ слова recompute намеренно: пересчитывать нечего — новый сезон пуст,
-- старый заморожен, ELO не меняется. Лишний пересчёт на деплое ни к чему.
--
-- Идемпотентность (миграция применяется раз, но autocommit без транзакции — при обрыве
-- деплоя возможен повтор): обе операции срабатывают ТОЛЬКО пока «Сезон 2026/2027» ещё не
-- заведён. Повторный прогон уже не снимет is_main с нового сезона и не задублирует его.
-- Подзапрос к ratings обёрнут в производную таблицу — обход ошибки MySQL 1093
-- (нельзя ссылаться на изменяемую таблицу напрямую).

UPDATE ratings SET is_main = 0, is_frozen = 1
WHERE is_main = 1
  AND NOT EXISTS (SELECT 1 FROM (SELECT id FROM ratings WHERE title = 'Сезон 2026/2027' LIMIT 1) AS chk);

