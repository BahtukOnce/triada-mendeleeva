-- Исправление клубного счёта в архиве (решение руководителя).
-- Счёт считался как ~Σ×Σ = Σ²/игры и никогда не был отрицательным: игрок с отрицательной суммой
-- получал плюс и стоял в таблице выше игроков с нулём. Миграция 079 исправила формулу
-- (~Σ×|Σ|) и пересчитала текущий сезон, но замороженные таблицы (is_frozen) не пересчитываются:
-- сезон 2025/2026, легаси-сезоны 2022–2025 и легаси-турниры. Их club_score посчитан нашим же
-- кодом той же формулой (rating_recompute / legacy_import.php) — это наша ошибка, не данные
-- источника, поэтому правим весь архив.
--
-- Разворот знака точно равен пересчёту по новой формуле: |счёт| = Σ²/игры не меняется, меняется
-- только знак; округление симметрично. Без условия по рейтингу — текущий сезон уже пересчитан
-- и под условие не попадает. Идемпотентно: после разворота club_score > 0 уже не выполняется.
-- peak_club не трогаем: он нужен только для топ-3 «Высший клубный счёт», куда такие игроки не
-- попадают. В имени нет recompute — пересчитывать нечего.

UPDATE rating_cache SET club_score = -club_score WHERE sum_total < 0 AND club_score > 0;
