-- Вечера, проведённые на сайте, не попадали в клубный рейтинг: rating_days заполнял
-- только импорт из Google-таблицы, а пересчёт берёт дни строго через JOIN rating_days.
-- Итог: ELO по таким играм считался, а Σ и клубный балл — нет (и протокол при этом
-- писал «рейтинг обновлён»). Дальше привязка делается автоматически при создании
-- вечера и при сохранении игры (day_attach_to_main_rating), здесь — разовый бэкофилл.
--
-- ГРАНИЦА СЕЗОНА ОБЯЗАТЕЛЬНА. Исторические вечера с mafiauniverse лежат как обычные
-- game_days без всякого флага, и из клубного рейтинга они исключены ИМЕННО отсутствием
-- строки в rating_days (см. inc/legacy_import.php). Привязать всё непривязанное — значит
-- влить сезоны 2022/23, 2023/24 и 2024/25 в текущий рейтинг. Все легаси-сезоны раньше
-- текущего, поэтому берём только дни от 1 сентября 2025 — начала сезона 2025/2026,
-- который сейчас и является основным рейтингом (миграция 045).
--
-- Идемпотентно: PRIMARY KEY (rating_id, day_id) + INSERT IGNORE.
-- В имени есть «recompute» — деплой сам пересчитает рейтинги после применения.
INSERT IGNORE INTO rating_days (rating_id, day_id)
SELECT r.id, d.id
FROM game_days d
CROSS JOIN ratings r
LEFT JOIN rating_days rd ON rd.day_id = d.id
WHERE r.is_main = 1
  AND rd.day_id IS NULL
  AND d.date >= '2025-09-01';
